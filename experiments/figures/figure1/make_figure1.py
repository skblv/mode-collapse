r"""Build the overview figure (Figure 1) of the paper.

Panels (b) and (c) are drawn with matplotlib's pgf backend so their text is
typeset by pdflatex in the paper's fonts; ``figure1.tex`` then places them
next to the TikZ panels (a) and (d). Requires pdflatex with TikZ.

Run from the repository root:
    uv run python experiments/figures/figure1/make_figure1.py
"""

import argparse
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

import matplotlib as mpl

mpl.use("pgf")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.lines import Line2D

from mode_collapse.paths import OUTPUT_DIR, RESULTS_DIR

# ---------------------------------------------------------------- config

FIGURE_TEX = Path(__file__).resolve().parent / "figure1.tex"
DIFFUSE_TERMS = Path("synthetic") / "diffuse_terms.csv"
ALIGNED_TERMS = Path("synthetic") / "aligned_terms.csv"
SURVEY_RATIOS = Path("surveys") / "survey_collision_ratio.csv"
CODENET_RATIOS = Path("codenet") / "codenet_collision_ratio.csv"

PGF_SETTINGS = {
    "pgf.texsystem": "pdflatex",
    "pgf.rcfonts": False,
    "pgf.preamble": r"\usepackage{times}\usepackage{amsmath}\usepackage{amssymb}",
    "font.family": "serif",
    "axes.linewidth": 0.5,
}

PALETTE = {
    "ink": "#000000",
    "muted": "#5A6570",
    "rule": "#8A939B",
    "under": "#57A75E",
    "over": "#9E2B23",
    "survey": "#1F4E79",
    "code": "#E08A5B",
    "neutral": "#BEC4C9",
    "bar": "#8A939B",
    "decide": "#98A2AA",
    "tint": "#F1F3F5",
    "tokblue": "#2F6F9F",
    "tokpink": "#C77DBB",
    "tokteal": "#3FA9A0",
    "tokgold": "#E8C15A",
    "tokgreen": "#1E7A3C",
}

LABEL_PT = 8.0
TICK_PT = 7.5
PANEL_SIGN_IN = (2.80, 1.95)
PANEL_CLOSE_IN = (2.60, 1.40)

SURVEYS = ["gss", "wvs", "anes"]
MODELS = ["gemma-2-2b-it", "qwen3.5-2b", "qwen3.5-4b", "gemma-3-4b-it"]
SURVEY_CHECKPOINTS = ["base", "early_stopped"]
CODENET_CHECKPOINTS = ["base", "fully_trained"]
CODENET_TRAINING_POINTS = 18
EXPECTED_RUNS = 16
EXPECTED_POINTS = 312

RATIO_LIMITS = (0.50, 3.55)
SIGN_Y_LIMITS = (0.45, 2.05)
SIGN_X_LIMITS = (-0.62, 3.62)
SIGN_Y_TICKS = [0.5, 1.0, 1.5, 2.0]
TERM_LABELS = ["Variance", "Squared bias", "Alignment", "Total"]
TERM_ROTATION = 45

RATIO_COLUMNS = [
    "collision_ratio_q05",
    "collision_ratio_q25",
    "collision_ratio_median",
    "collision_ratio_q75",
    "collision_ratio_q95",
]


@dataclass(frozen=True)
class Run:
    """One model-dataset trajectory of the median collision ratio."""

    kind: str
    run_id: str
    examples: np.ndarray
    ratios: np.ndarray


def write_palette(build_dir: Path) -> None:
    """Write the colors shared by TikZ and matplotlib.

    Args:
        build_dir: Directory for the generated parts.
    """
    lines = ["% generated by make_figure1.py -- do not edit"]
    for name, hex_value in PALETTE.items():
        lines.append(rf"\definecolor{{{name}}}{{HTML}}{{{hex_value.lstrip('#')}}}")
    (build_dir / "palette.tex").write_text("\n".join(lines) + "\n")


def validate_ratio_summary(arm_ratio_df: pd.DataFrame, name: str) -> None:
    """Check that the quantile summaries are finite, positive, and ordered.

    Args:
        arm_ratio_df: One row per arm with collision-ratio quantiles.
        name: Dataset name used in the error message.

    Raises:
        ValueError: If any quantile is nonfinite, nonpositive, or unordered.
    """
    values = arm_ratio_df[RATIO_COLUMNS].to_numpy(float)
    if not np.isfinite(values).all() or not (values > 0).all():
        raise ValueError(f"nonpositive or nonfinite ratio summary: {name}")
    if not (np.diff(values, axis=1) >= 0).all():
        raise ValueError(f"unordered ratio quantiles: {name}")


def load_runs(results_dir: Path) -> list[Run]:
    """Load the 12 survey runs and the four CodeNet runs.

    Survey runs use the base and early-stopped checkpoints; CodeNet runs use
    the base and final checkpoints, as in the body figures.

    Args:
        results_dir: Directory holding the result files.

    Returns:
        The 16 trajectories, surveys first.

    Raises:
        ValueError: If a trajectory is missing, incomplete, or invalid.
    """
    arm_ratio_survey_df = pd.read_csv(results_dir / SURVEY_RATIOS)
    is_plotted = arm_ratio_survey_df["checkpoint"].isin(SURVEY_CHECKPOINTS)
    arm_ratio_survey_df = arm_ratio_survey_df[is_plotted]
    validate_ratio_summary(arm_ratio_survey_df, "surveys")
    runs = []
    survey_arms = [(survey, model) for survey in SURVEYS for model in MODELS]
    for survey, model in survey_arms:
        is_arm = (arm_ratio_survey_df["dataset"] == survey) & (
            arm_ratio_survey_df["model"] == model
        )
        arm_df = arm_ratio_survey_df[is_arm].sort_values("n")
        runs.append(
            Run(
                "survey",
                f"{survey}/{model}",
                arm_df["n"].to_numpy(float),
                arm_df["collision_ratio_median"].to_numpy(),
            )
        )

    arm_ratio_codenet_df = pd.read_csv(results_dir / CODENET_RATIOS)
    is_plotted = arm_ratio_codenet_df["checkpoint"].isin(CODENET_CHECKPOINTS)
    arm_ratio_codenet_df = arm_ratio_codenet_df[is_plotted]
    validate_ratio_summary(arm_ratio_codenet_df, "CodeNet")
    expected_counts = {"base": 1, "fully_trained": CODENET_TRAINING_POINTS}
    for model in MODELS:
        arm_df = arm_ratio_codenet_df[
            arm_ratio_codenet_df["model"] == model
        ].sort_values("n")
        checkpoint_counts = arm_df.groupby("checkpoint").size().to_dict()
        if checkpoint_counts != expected_counts:
            raise ValueError(
                f"incomplete Zhang-Shasha trace for {model}: {checkpoint_counts}"
            )
        runs.append(
            Run(
                "code",
                f"codenet/{model}",
                arm_df["n"].to_numpy(float),
                arm_df["collision_ratio_median"].to_numpy(),
            )
        )

    points = sum(len(run.examples) for run in runs)
    if len(runs) != EXPECTED_RUNS or points != EXPECTED_POINTS:
        raise ValueError(
            f"expected {EXPECTED_RUNS} curves and {EXPECTED_POINTS} points"
        )
    for run in runs:
        is_valid = np.isfinite(run.ratios).all() and (run.ratios > 0).all()
        if run.examples[0] != 0 or not is_valid:
            raise ValueError(f"invalid collision-ratio trajectory: {run.run_id}")
    return runs


def assert_not_clipped(fig: plt.Figure, name: str) -> None:
    """Fail if any artist reaches past the edges of the figure.

    Args:
        fig: Figure to check.
        name: Panel name used in the error message.

    Raises:
        ValueError: If content would be cut off in the PDF.
    """
    fig.canvas.draw()
    tight = fig.get_tightbbox(fig.canvas.get_renderer())
    width, height = fig.get_size_inches()
    slack = {
        "left": tight.x0,
        "bottom": tight.y0,
        "right": width - tight.x1,
        "top": height - tight.y1,
    }
    if min(slack.values()) <= -0.002:
        rounded = {side: round(value, 4) for side, value in slack.items()}
        raise ValueError(f"{name} is clipped: {rounded}")


def style_axes(ax: plt.Axes) -> None:
    """Keep the left and bottom spines only, in the rule color.

    Args:
        ax: Axes to style.
    """
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_linewidth(0.5)
        ax.spines[side].set_color(PALETTE["rule"])
    ax.tick_params(
        labelsize=TICK_PT,
        length=2.0,
        width=0.5,
        color=PALETTE["rule"],
        labelcolor=PALETTE["ink"],
        pad=1.6,
    )


def write_panel_sign(results_dir: Path, build_dir: Path) -> None:
    """Draw panel (b): the decomposition as a waterfall in two settings.

    Each term is normalized by target collision per context and averaged over
    contexts and 100 fits. The bars start at R = 1 and end at 1 + ``measured``,
    the mean collision ratio. The diffuse case is the smallest sample size; the
    mode-aligned case is the sample size with the largest alignment term.

    Args:
        results_dir: Directory holding the result files.
        build_dir: Directory for the generated parts.

    Raises:
        ValueError: If the terms do not sum to the measured gap or leave the axes.
    """
    size_term_diffuse_df = pd.read_csv(results_dir / DIFFUSE_TERMS).sort_values("N")
    size_term_aligned_df = pd.read_csv(results_dir / ALIGNED_TERMS).sort_values("N")
    case_over = size_term_diffuse_df.loc[size_term_diffuse_df["N"].idxmin()]
    case_under = size_term_aligned_df.loc[size_term_aligned_df["cross_term"].idxmax()]

    fig, axes = plt.subplots(1, 2, figsize=PANEL_SIGN_IN, sharey=True)
    fig.subplots_adjust(left=0.153, right=0.995, top=0.775, bottom=0.269, wspace=0.16)
    cases = {"over": (axes[0], case_over), "under": (axes[1], case_under)}
    for ax, row in cases.values():
        gap = float(row["measured"])
        terms = [
            float(row["var_term"]),
            float(row["bias2_term"]),
            float(row["cross_term"]),
        ]
        if terms[0] < 0 or terms[1] < 0 or abs(sum(terms) - gap) >= 1e-12:
            raise ValueError(f"inconsistent decomposition terms: {terms}, gap {gap}")
        color = PALETTE["over"] if gap < 0 else PALETTE["under"]
        title = "over-diverse" if gap < 0 else "under-diverse"
        ax.set_title(title, fontsize=LABEL_PT, color=color, pad=3.0, linespacing=1.25)
        ax.axhline(1, color=PALETTE["muted"], lw=0.7, zorder=3)

        running = 1.0
        low = high = 1.0
        for index, term in enumerate(terms):
            ax.bar(
                index,
                term,
                bottom=running,
                width=0.70,
                color=PALETTE["bar"],
                lw=0,
                zorder=2,
            )
            if index < 2:
                ax.plot(
                    [index + 0.35, index + 1 - 0.35],
                    [running + term, running + term],
                    color=PALETTE["rule"],
                    lw=0.45,
                    ls=(0, (1.1, 1.2)),
                    zorder=4,
                )
            running += term
            low, high = min(low, running), max(high, running)
        if abs(running - (1.0 + gap)) >= 1e-12:
            raise ValueError(f"waterfall ends at {running}, expected {1.0 + gap}")
        ax.bar(3, gap, bottom=1.0, width=0.70, color=color, lw=0, zorder=2)
        if not (SIGN_Y_LIMITS[0] < low and high < SIGN_Y_LIMITS[1]):
            raise ValueError(f"waterfall leaves the axes: {low}, {high}")

        ax.set_xticks(range(4))
        ax.set_xticklabels(
            TERM_LABELS,
            fontsize=TICK_PT,
            rotation=TERM_ROTATION,
            ha="right",
            rotation_mode="anchor",
        )
        for label in ax.get_xticklabels():
            label.set_color(PALETTE["ink"])
        ax.set_xlim(*SIGN_X_LIMITS)
        ax.set_ylim(*SIGN_Y_LIMITS)
        style_axes(ax)
        ax.spines["left"].set_bounds(SIGN_Y_TICKS[0], SIGN_Y_TICKS[-1])

    axes[1].spines["left"].set_visible(False)
    axes[1].tick_params(axis="y", length=0)
    axes[0].set_yticks(SIGN_Y_TICKS)
    axes[0].set_yticklabels([r"$0.5$", r"$1$", r"$1.5$", r"$2$"], fontsize=TICK_PT)
    axes[0].set_ylabel(r"$R$", fontsize=LABEL_PT, labelpad=1.5, color=PALETTE["ink"])
    assert_not_clipped(fig, "panel_sign")
    fig.savefig(build_dir / "panel_sign.pdf", transparent=True)
    plt.close(fig)


def write_panel_close(runs: list[Run], build_dir: Path) -> None:
    """Draw panel (c): median collision ratio against fine-tuning examples.

    Every line is one run; zero examples is the base model.

    Args:
        runs: The 16 trajectories.
        build_dir: Directory for the generated parts.
    """
    fig, ax = plt.subplots(figsize=PANEL_CLOSE_IN)
    fig.subplots_adjust(left=0.128, right=0.990, top=0.957, bottom=0.255)
    ax.axhline(1.0, color=PALETTE["muted"], lw=0.9, ls=(0, (2.6, 1.8)), zorder=2)
    for run in runs:
        color = PALETTE["survey"] if run.kind == "survey" else PALETTE["code"]
        ax.plot(
            run.examples,
            run.ratios,
            "-",
            color=color,
            lw=0.55,
            alpha=0.50,
            zorder=3,
            solid_capstyle="round",
        )
        ax.plot(
            run.examples[0],
            run.ratios[0],
            "o",
            color=color,
            ms=3.0,
            mew=0,
            alpha=0.95,
            zorder=6,
        )

    ax.set_xscale("symlog", linthresh=8)
    ax.set_yscale("log")
    ax.set_xlim(-2.6, 7e6)
    ax.set_ylim(*RATIO_LIMITS)
    ax.set_xticks([0, 1e2, 1e4, 1e6])
    ax.set_xticklabels(["0", "100", "10k", "1M"])
    ax.xaxis.set_minor_locator(mpl.ticker.NullLocator())
    ax.set_yticks([0.6, 1.0, 2.0, 3.0])
    ax.set_yticklabels(["0.6", "1", "2", "3"])
    ax.yaxis.set_minor_locator(mpl.ticker.NullLocator())
    style_axes(ax)
    ax.spines["left"].set_bounds(*RATIO_LIMITS)
    ax.set_ylabel(r"$R$", fontsize=LABEL_PT, labelpad=1.5, color=PALETTE["ink"])
    ax.set_xlabel(
        r"fine-tuning examples", fontsize=LABEL_PT, labelpad=1.5, color=PALETTE["ink"]
    )

    handles = [
        Line2D(
            [0],
            [0],
            color=PALETTE["survey"],
            lw=0.9,
            marker="o",
            ms=3.0,
            mew=0,
            label="surveys (12 curves)",
        ),
        Line2D(
            [0],
            [0],
            color=PALETTE["code"],
            lw=0.9,
            marker="o",
            ms=3.0,
            mew=0,
            label="programs: CodeNet (4)",
        ),
    ]
    legend = ax.legend(
        handles=handles,
        loc="upper right",
        bbox_to_anchor=(6.5e6, 3.30),
        bbox_transform=ax.transData,
        frameon=False,
        fontsize=TICK_PT,
        handlelength=1.2,
        handletextpad=0.5,
        labelspacing=0.35,
        borderpad=0.0,
        borderaxespad=0.0,
    )
    for text in legend.get_texts():
        text.set_color(PALETTE["ink"])
    assert_not_clipped(fig, "panel_close")
    fig.savefig(build_dir / "panel_close.pdf", transparent=True)
    plt.close(fig)


def main() -> None:
    """Write the generated parts, compile the figure, and copy the PDF."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    parser.add_argument("--out-dir", type=Path, default=OUTPUT_DIR / "figures")
    args = parser.parse_args()
    build_dir = args.out_dir / "figure1_build"
    build_dir.mkdir(parents=True, exist_ok=True)
    mpl.rcParams.update(PGF_SETTINGS)

    write_palette(build_dir)
    write_panel_sign(args.results_dir, build_dir)
    write_panel_close(load_runs(args.results_dir), build_dir)
    command = [
        "pdflatex",
        "-interaction=nonstopmode",
        "-halt-on-error",
        "-jobname=figure1",
        str(FIGURE_TEX),
    ]
    log_path = build_dir / "pdflatex.log"
    with log_path.open("w") as log_file:
        result = subprocess.run(
            command,
            cwd=build_dir,
            stdout=log_file,
            stderr=subprocess.STDOUT,
            check=False,
        )
    if result.returncode != 0:
        raise RuntimeError(
            f"pdflatex failed with code {result.returncode}; see {log_path}"
        )
    shutil.copyfile(build_dir / "figure1.pdf", args.out_dir / "figure1.pdf")
    print(f"Wrote {args.out_dir / 'figure1.pdf'}")


if __name__ == "__main__":
    main()
